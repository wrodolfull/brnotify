import express,{type ErrorRequestHandler} from 'express';
import cors from 'cors';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import {env} from './config.js';
import {router} from './routes.js';
import {publicApiRouter} from './public-api.js';
import {integrationAdminRouter} from './integration-admin.js';
import {reportRouter} from './reports.js';
import {mediaRouter} from './goto-media.js';
import {gotoTestRouter} from './goto-test.js';
import {templateLibraryRouter} from './template-library-routes.js';
import {ApiOperationError} from './external-operations.js';
import {WebhookConfigurationError} from './outbound-webhooks.js';
import {DispatchPacingError} from './send-pacing.js';
import {ProviderError} from './goto.js';
import {pool} from './db.js';
const app=express();
app.disable('x-powered-by');
app.set('trust proxy',1);
app.use(helmet());
app.use(cors({origin:env.WEB_URL,methods:['GET','POST','PUT','PATCH','DELETE'],allowedHeaders:['Authorization','Content-Type','x-tenant-id']}));
app.use(express.json({limit:'1mb'}));
app.use(rateLimit({windowMs:60_000,limit:180,standardHeaders:'draft-7',legacyHeaders:false}));
app.use('/v1',publicApiRouter);
app.use('/api/integrations',integrationAdminRouter);
app.use('/api/reports',reportRouter);
app.use('/api/goto/media',mediaRouter);
app.use('/api/goto/templates',gotoTestRouter);
app.use('/api/template-library',templateLibraryRouter);
app.use(router);
app.use((req,res)=>res.status(404).json({error:'Rota não encontrada'}));
const errorHandler:ErrorRequestHandler=(err,_req,res,_next)=>{
 if(err instanceof DispatchPacingError){res.setHeader('Retry-After',String(Math.ceil(err.waitMs/1000)));return void res.status(429).json({error:err.message})}
 if(err instanceof ProviderError){
  const status=err.status===429?429:err.status>=400&&err.status<500?err.status:502;
  if(status===429)res.setHeader('Retry-After',String(Math.ceil(Math.max(err.retryAfterMs??0,30000)/1000)));
  return void res.status(status).json({error:err.message});
 }
 if(err instanceof ApiOperationError)return void res.status(err.code).json({error:err.message});
 if(err instanceof WebhookConfigurationError)return void res.status(422).json({error:err.message});
 if(err?.name==='ZodError')return void res.status(422).json({error:'Dados inválidos',details:err.issues});
 if(err?.code==='23505')return void res.status(409).json({error:'Registro duplicado'});
 if(err?.code==='23503')return void res.status(422).json({error:'Referência inválida'});
 if(err?.code==='LIMIT_FILE_SIZE')return void res.status(413).json({error:'Arquivo excede o limite de upload configurado'});
 console.error('[API]',err instanceof Error?err.message:'Erro inesperado');
 res.status(500).json({error:env.NODE_ENV==='production'?'Erro interno':err?.message||'Erro interno'});
};
app.use(errorHandler);
const server=app.listen(env.PORT,()=>console.log('BR Notify API ativa na porta '+env.PORT));
process.on('SIGTERM',()=>{server.close(()=>pool.end())});
